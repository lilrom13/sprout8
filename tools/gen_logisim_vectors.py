#!/usr/bin/env python3
"""Generate Logisim-evolution test vectors for the Sprout-8 modules.

Writes one test-vector file per module. Load it in Logisim with Simulate -> Test Vector
on the matching subcircuit, or run it headless:

    logisim-evolution --test-vector alu build/logisim/vectors/alu.txt hw/logisim/sprout8.circ

The column names are the port names of the module specification
(docs/spec/sprout8-module-spec.md), so the subcircuit's pin labels must match them.

Modules:
    alu   spec section 9: directed edge cases (tb_alu, Appendix C2-C5), every op over all
          pairs of corner values, and random cases. --exhaustive writes all 524,288 cases.
    pc    spec section 4: the tb_pc sequence (reset priority, hold, 256 increments with
          wrap, every load value, load beats inc) as one sequential test.

Clocked modules use Logisim's sequential test vectors (<set> and <seq> columns: the state
is kept from one row to the next within a set). The module's clock is an input pin named
`clk`, so the vector drives it: every clock cycle is two rows, first clk=0 with the new
inputs (outputs must still show the old state), then clk=1 (outputs show the new state).
Keeping the inputs stable across the rising edge avoids a race between data and clock.

Usage:
    python3 tools/gen_logisim_vectors.py                       # all modules -> build/logisim/vectors/
    python3 tools/gen_logisim_vectors.py alu --random 5000 --seed 7
    python3 tools/gen_logisim_vectors.py alu --exhaustive
"""
from __future__ import annotations

import argparse
import itertools
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "build" / "logisim" / "vectors"
DC = "<DC>"   # don't care

# ALU operation codes, module spec section 2.2 (binding: tb_alu drives op as 0..7)
ALU_OPS = ["ADD", "SUB", "AND", "OR", "XOR", "SHL", "SHR", "PASB"]
CORNERS = [0x00, 0x01, 0x02, 0x0F, 0x10, 0x55, 0x7F, 0x80, 0x81, 0xAA, 0xF0, 0xFE, 0xFF]


def alu_model(op: int, a: int, b: int) -> tuple[int, int, int, int]:
    """Return (y, z, c, n), written from the spec table rather than from any circuit."""
    name = ALU_OPS[op]
    c = 0
    if name == "ADD":
        y = (a + b) % 256
        c = int(a + b > 255)
    elif name == "SUB":
        y = (a - b) % 256
        c = int(a < b)
    elif name == "AND":
        y = a & b
    elif name == "OR":
        y = a | b
    elif name == "XOR":
        y = a ^ b
    elif name == "SHL":
        y = (a * 2) % 256
        c = a >> 7
    elif name == "SHR":
        y = a // 2
        c = a & 1
    else:                                   # PASB
        y = b
    return y, int(y == 0), c, y >> 7


def alu_vectors(n_random: int, seed: int, exhaustive: bool) -> list[str]:
    # Multi-bit values are written as 0x.. hex: Logisim reads unprefixed values as signed decimal
    def row(op: int, a: int, b: int, note: str = "") -> str:
        y, z, c, n = alu_model(op, a, b)
        line = f"0x{a:02x} 0x{b:02x} 0x{op:x}   0x{y:02x} {z} {c} {n}"
        return f"{line}   # {note}" if note else line

    lines = [
        "# Sprout-8 ALU test vectors (module spec section 9), generated by tools/gen_logisim_vectors.py",
        "# op: 0 ADD  1 SUB  2 AND  3 OR  4 XOR  5 SHL  6 SHR  7 PASB",
        "a[8] b[8] op[3]   y[8] z c n",
        "",
        "# directed edge cases (tb_alu, Appendix C)",
        row(0, 0xFF, 0x01, "C2 ADD FF+01: zero and carry"),
        row(1, 0x03, 0x05, "C3 SUB 03-05: borrow and negative"),
        row(1, 0x05, 0x05, "SUB equal: Z set, no borrow"),
        row(3, 0x00, 0x01, "C4 OR clears C"),
        row(6, 0x81, 0x00, "C5 SHR 81: carry is old bit 0"),
        row(5, 0x80, 0x00, "SHL 80: carry is old bit 7, result zero"),
        row(0, 0xFF, 0x01, "INC FF (ADD with b = 1) sets C"),
        row(1, 0x00, 0x01, "DEC 00 (SUB with b = 1) wraps to FF, sets C and N"),
        "",
    ]
    if exhaustive:
        lines.append("# exhaustive: every op x every a x every b")
        lines += [row(op, a, b) for op in range(8) for a in range(256) for b in range(256)]
        return lines

    lines.append("# every op over all pairs of corner values")
    lines += [row(op, a, b) for op in range(8) for a, b in itertools.product(CORNERS, repeat=2)]
    lines += ["", f"# {n_random} random cases (seed {seed})"]
    rng = random.Random(seed)
    lines += [row(rng.randrange(8), rng.randrange(256), rng.randrange(256)) for _ in range(n_random)]
    return lines


def fmt(value: int | str, width: int) -> str:
    if isinstance(value, str):
        return value
    return str(value) if width == 1 else f"0x{value:0{(width + 3) // 4}x}"


class Sequence:
    """Rows of one sequential test set, two rows per clock cycle."""

    def __init__(self, inputs: dict[str, int], outputs: dict[str, int], set_no: int = 1):
        self.inputs, self.outputs, self.set_no = inputs, outputs, set_no
        self.header = "<set> <seq> clk " + " ".join(
            f"{n}[{w}]" if w > 1 else n for n, w in {**inputs, **outputs}.items())
        self.lines: list[str] = []
        self.seq = 0

    def _row(self, clk: int, ins: dict, outs: dict) -> str:
        self.seq += 1
        cells = [str(self.set_no), str(self.seq), str(clk)]
        cells += [fmt(ins[n], w) for n, w in self.inputs.items()]
        cells += [fmt(outs[n], w) for n, w in self.outputs.items()]
        return " ".join(cells)

    def comment(self, text: str) -> None:
        self.lines.append(f"# {text}")

    def cycle(self, ins: dict, before: dict, after: dict) -> None:
        """Apply `ins`, expect `before` while clk is low, then `after` the rising edge."""
        self.lines.append(self._row(0, ins, before))
        self.lines.append(self._row(1, ins, after))


def pc_vectors(n_random: int, seed: int, exhaustive: bool) -> list[str]:
    seq = Sequence({"rst": 1, "inc": 1, "load": 1, "d": 8}, {"q": 8})
    q = 0

    def cycle(rst=0, inc=0, load=0, d=0, note=""):
        nonlocal q
        if note:
            seq.comment(note)
        nxt = 0 if rst else d if load else (q + 1) % 256 if inc else q
        # reset may act at once (the Clear pin, spec 1.3) or at the edge: either is allowed
        before = DC if rst or seq.seq == 0 else q
        seq.cycle({"rst": rst, "inc": inc, "load": load, "d": d}, {"q": before}, {"q": nxt})
        q = nxt

    cycle(rst=1, inc=1, load=1, d=0xAA, note="reset beats load and inc")
    cycle(note="hold")
    cycle()
    seq.comment("256 increments: every value, then 0xFF wraps to 0x00")
    for _ in range(256):
        cycle(inc=1)
    seq.comment("load every value")
    for v in range(256):
        cycle(load=1, d=v)
    cycle(load=1, inc=1, d=0x40, note="load beats inc")
    cycle(inc=1, note="inc after load")
    cycle(load=1, d=0xFF, note="0xFF + 1 wraps to 0x00 (C7)")
    cycle(inc=1)
    cycle(load=1, d=0x5A, note="reset from a non-zero value")
    cycle(rst=1)

    return ["# Sprout-8 PC test vectors (module spec section 4), generated by tools/gen_logisim_vectors.py",
            "# one sequential set; each clock cycle is two rows: clk=0 (no change yet), clk=1 (after the edge)",
            seq.header, ""] + seq.lines


MODULES = {"alu": alu_vectors, "pc": pc_vectors}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("modules", nargs="*", choices=MODULES, help="modules to generate (default: all)")
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT,
                    help=f"output directory (default: {DEFAULT_OUT.relative_to(ROOT)})")
    ap.add_argument("--random", type=int, default=2000, help="random cases per module (default: 2000)")
    ap.add_argument("--seed", type=int, default=2026, help="random seed (default: 2026)")
    ap.add_argument("--exhaustive", action="store_true", help="every input combination (alu: 524,288 rows)")
    args = ap.parse_args(argv)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    for mod in args.modules or MODULES:
        lines = MODULES[mod](args.random, args.seed, args.exhaustive)
        dst = args.out_dir / f"{mod}.txt"
        dst.write_text("\n".join(lines) + "\n")
        n_rows = sum(1 for ln in lines if ln and not ln.startswith("#")) - 1   # minus the header
        print(f"{mod}: {n_rows} vectors -> {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
